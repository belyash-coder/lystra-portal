// AUTH_SECRET подписывает и проверяет JWT для мобильного входа и входа через
// TMA. Раньше во всех местах использования был публичный дефолт-фолбэк
// ('lystra-super-secret-key') — если переменную окружения забыли задать на
// сервере, эта строка (видна в открытом исходном коде) становилась реальным
// секретом, и кто угодно мог подделать токен любого пользователя. Теперь без
// реального значения в окружении токены просто не создаются и не
// проверяются — это должно вызываться внутри try/catch, вызывающего кода.
export function getAuthSecret(): string {
  const secret = process.env.AUTH_SECRET;
  if (!secret) throw new Error('AUTH_SECRET не настроен');
  return secret;
}
